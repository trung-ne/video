function b(
  marker: string,
  focus: string,
  grammar: VisualGrammar,
  n: number,
): AuthoredScene {
  const prop = props[n % props.length],
    who = people[n % people.length];
  const emotion: Emotion =
    n % 5 === 0 ? "concern" : n % 7 === 0 ? "surprise" : "neutral";
  const base = {
    marker,
    grammar,
    emotion,
    purpose: `Make the viewer understand ${focus} as one distinct beat.`,
    viewerFocus: focus,
    visualRegister: "character_action" as const,
    focalType: "character_action" as const,
    semanticVisual: {
      subject: focus,
      action: "appears as the focal beat",
      takeaway: focus,
    },
    silentFrameTakeaway: focus,
    focalOccupancyTarget: 0.46,
  };
  if (grammar === "EVIDENCE")
    return {
      ...base,
      visualRegister: "evidence",
      focalType: "evidence",
      slots: { title: focus, body: focus },
    };
  if (grammar === "QA_REVEAL")
    return {
      ...base,
      visualRegister: "infographic",
      focalType: "diagram",
      slots: { q: focus + "?", a: "Cần nhìn vào cơ chế phía sau." },
    };
  if (
    grammar === "ICON_TRIPLE" ||
    grammar === "DIAGRAM" ||
    grammar === "POLICY_LIST"
  )
    return {
      ...base,
      visualRegister: "infographic",
      focalType: "diagram",
      slots: {
        items: focus + "|Áp lực|Hệ quả",
        icons: `${prop}|finance/debt|finance/trending_down`,
      },
    };
  if (grammar === "COMPARE")
    return {
      ...base,
      visualRegister: "infographic",
      focalType: "chart",
      slots: {
        left: "Trước",
        right: "Sau",
        leftAsset: prop,
        rightAsset: "finance/trending_down",
      },
    };
  if (grammar === "CAUSE_EFFECT")
    return {
      ...base,
      visualRegister: "infographic",
      focalType: "diagram",
      slots: {
        cause: focus,
        effect: "Hệ quả tăng lên",
        causeIcon: prop,
        effectIcon: "finance/trending_down",
      },
    };
  if (grammar === "STAT_REVEAL")
    return {
      ...base,
      visualRegister: "evidence",
      focalType: "chart",
      slots: { stat: focus, anchor: prop, caption: focus },
    };
  if (grammar === "PHOTO_EVIDENCE")
    return {
      ...base,
      visualRegister: "photo_broll",
      focalType: "photo",
      characterRequired: false,
      photoTreatment: "cutaway",
      slots: { photo: "backgrounds/office_trading.jpg", caption: focus },
    };
  if (grammar === "DIALOGUE_QA")
    return {
      ...base,
      slots: {
        asker: "host",
        answerer: "trader",
        askerText: "Điều gì đang xảy ra?",
        answererText: focus,
      },
    };
  if (grammar === "VISUAL_METAPHOR")
    return {
      ...base,
      visualRegister: "visual_gag",
      focalType: "visual_gag",
      slots: {
        setup: focus,
        payoff: "Rủi ro khuếch đại",
        leftAsset: prop,
        rightAsset: "finance/loss",
      },
    };
  if (grammar === "TABLEAU")
    return {
      ...base,
      visualRegister: "full_tableau",
      focalType: "full_scene",
      slots: {
        stage: "assets/scenes/office_desk.svg",
        who,
        anchorA: "desk",
        prop,
      },
    };
  return { ...base, slots: { who, prop, label: focus } };
}

